//! Multi-model training: a generator and a discriminator, each a graph, trained against each other.

use crate::codegen::{feats_literal, generate_models};
use crate::compound::BlockLibrary;
use crate::graph::{fmt_shape, Dim, GanSpec, GanTraining, GraphError, ValidatedGraph};

#[derive(Debug, Clone)]
pub struct ValidatedGan {
    pub generator: ValidatedGraph,
    pub discriminator: ValidatedGraph,
    pub training: GanTraining,
}

fn bad(msg: impl Into<String>) -> GraphError {
    GraphError::Training(msg.into())
}

impl GanSpec {
    pub fn validate(&self) -> Result<ValidatedGan, GraphError> {
        self.validate_with(&BlockLibrary::global())
    }

    /// Both graphs must validate, and their interface must fit: noise in, a data-shaped sample out, which the
    /// discriminator turns into one logit.
    pub fn validate_with(&self, lib: &BlockLibrary) -> Result<ValidatedGan, GraphError> {
        let wrap = |who: &str, e: GraphError| bad(format!("{who}: {e}"));
        let generator = self.generator.validate_with(lib).map_err(|e| wrap("generator", e))?;
        let discriminator = self.discriminator.validate_with(lib).map_err(|e| wrap("discriminator", e))?;
        let t = &self.training;

        let one = |g: &ValidatedGraph, who: &str| -> Result<(String, String), GraphError> {
            if g.spec.inputs.len() != 1 || g.outputs.len() != 1 {
                return Err(bad(format!("the {who} needs exactly one input and one output")));
            }
            Ok((g.spec.inputs.keys().next().unwrap().clone(), g.outputs.keys().next().unwrap().clone()))
        };
        let (g_in, g_out) = one(&generator, "generator")?;
        let (d_in, d_out) = one(&discriminator, "discriminator")?;

        let z = &generator.spec.inputs[&g_in];
        if z.len() != 2 || z[1] != Dim::Const(t.latent as i64) {
            return Err(bad(format!("the generator's input must be [B, {}] (the latent size), found {}", t.latent, fmt_shape(z))));
        }
        let sample = generator.shape_of(&generator.outputs[&g_out]).clone();
        let want = Dim::Const(t.data.features.len() as i64);
        if sample.len() != 2 || sample[1] != want {
            return Err(bad(format!("the generator must output [B, {}] (one value per feature column), found {}", t.data.features.len(), fmt_shape(&sample))));
        }
        let d_x = &discriminator.spec.inputs[&d_in];
        if d_x != &sample {
            return Err(bad(format!("the discriminator's input {} must equal the generator's output {}", fmt_shape(d_x), fmt_shape(&sample))));
        }
        let logit = discriminator.shape_of(&discriminator.outputs[&d_out]);
        if logit.len() != 2 || logit[1] != Dim::Const(1) {
            return Err(bad(format!("the discriminator must output one logit per sample, [B, 1], found {}", fmt_shape(logit))));
        }
        if t.d_steps == 0 || t.epochs == 0 {
            return Err(bad("d_steps and epochs must be at least 1"));
        }
        Ok(ValidatedGan { generator, discriminator, training: t.clone() })
    }
}

pub fn generate_gan_script(v: &ValidatedGan, id: &str) -> Result<String, GraphError> {
    let t = &v.training;
    if !(t.beta1 >= 0.0 && t.beta1 < 1.0) {
        return Err(bad("beta1 must be in [0, 1)"));
    }
    let models = generate_models(&[("Generator", &v.generator), ("Discriminator", &v.discriminator)]);
    let feats = feats_literal(&t.data.features);
    let bs = t.batch_size.map(|b| b.to_string()).unwrap_or_else(|| "len(X)".into());
    let cfg = serde_json::to_string(&serde_json::json!({
        "graph": id, "kind": "gan", "latent": t.latent, "epochs": t.epochs, "batch_size": t.batch_size,
        "lr_g": t.lr_g, "lr_d": t.lr_d, "beta1": t.beta1, "d_steps": t.d_steps,
    }))
    .unwrap();
    Ok(format!(
        r#"# Generated by Sentinel from GAN component: {id}
# Standalone PyTorch. Sentinel tracking is used only if the `sentinel` SDK is importable.
import csv
import json
import torch
import torch.nn as nn

{models}

torch.manual_seed({seed})
with open({csv:?}, newline="") as f:
    rows = list(csv.DictReader(f, skipinitialspace=True))
_total = len(rows)
rows = [r for r in rows if all((r.get(c) or "").strip() != "" for c in [{feats}])]
if len(rows) < _total:
    print(f"skipped {{_total - len(rows)}} rows with missing values", flush=True)
if not rows:
    raise SystemExit("no usable rows in " + {csv:?})
X = torch.tensor([[float(r[c]) for c in [{feats}]] for r in rows], dtype=torch.float32)

LATENT = {latent}
G, D = Generator(), Discriminator()
opt_g = torch.optim.Adam(G.parameters(), lr={lr_g}, betas=({beta1}, 0.999))
opt_d = torch.optim.Adam(D.parameters(), lr={lr_d}, betas=({beta1}, 0.999))
bce = nn.BCEWithLogitsLoss()

N_PARAMS = sum(p.numel() for p in G.parameters()) + sum(p.numel() for p in D.parameters())
print(f"generator + discriminator: {{N_PARAMS:,}} parameters", flush=True)

try:
    import sentinel
    sentinel.init(run_name={id:?}, config={{**json.loads({cfg:?}), "n_params": N_PARAMS}})
except Exception:
    sentinel = None

BATCH = {bs}
EPOCHS = {epochs}
for epoch in range(EPOCHS):
    G.train(True)
    D.train(True)
    order = torch.randperm(len(X))
    for i in range(0, len(X), BATCH):
        real = X[order[i:i + BATCH]]
        n = len(real)
        for _ in range({d_steps}):
            fake = G(torch.randn(n, LATENT)).detach()
            d_loss = bce(D(real), torch.ones(n, 1)) + bce(D(fake), torch.zeros(n, 1))
            opt_d.zero_grad()
            d_loss.backward()
            opt_d.step()
        g_loss = bce(D(G(torch.randn(n, LATENT))), torch.ones(n, 1))
        opt_g.zero_grad()
        g_loss.backward()
        opt_g.step()
    if epoch % 10 == 0 or epoch == EPOCHS - 1:
        G.train(False)
        D.train(False)
        with torch.no_grad():
            s = G(torch.randn(2000, LATENT))
            mean_gap = (s.mean(0) - X.mean(0)).abs().mean().item()
            std_gap = (s.std(0) - X.std(0)).abs().mean().item()
        print(f"epoch {{epoch:3d}} d_loss {{d_loss.item():.4f}} g_loss {{g_loss.item():.4f}} mean_gap {{mean_gap:.4f}} std_gap {{std_gap:.4f}}", flush=True)
        if sentinel:
            sentinel.log({{"d_loss": d_loss.item(), "g_loss": g_loss.item(), "mean_gap": mean_gap, "std_gap": std_gap}}, step=epoch)

# ---- export: both networks, a TorchScript generator, and metadata -----------------------------------------
import os
import pathlib
import shutil

_run = sentinel.get_run() if sentinel else None
_art = pathlib.Path(_run.artifacts_dir) if _run is not None else pathlib.Path(os.environ.get("SENTINEL_ARTIFACT_DIR", "artifacts"))
_art.mkdir(parents=True, exist_ok=True)
G.train(False)
D.train(False)
torch.save(G.state_dict(), _art / "generator.pt")
torch.save(D.state_dict(), _art / "discriminator.pt")
_files = {{"generator": "generator.pt", "discriminator": "discriminator.pt"}}
try:
    torch.jit.trace(G, torch.randn(1, LATENT), check_trace=False).save(str(_art / "generator_script.pt"))
    _files["generator_script"] = "generator_script.pt"
except Exception as _e:
    print("torchscript export skipped:", _e, flush=True)
with open(_art / "meta.json", "w") as _f:
    json.dump({{
        "graph": {id:?}, "task": "gan", "features": [{feats}], "target": None, "classes": None, "latent": LATENT,
        "input_shape": [LATENT], "loss": "gan", "n_params": N_PARAMS, "test_mean_gap": mean_gap, "test_std_gap": std_gap,
        "torch": torch.__version__, "files": _files,
    }}, _f, indent=2)
shutil.copyfile(__file__, _art / "train.py")
print("artifacts saved to", _art, flush=True)
if sentinel:
    sentinel.finish()
"#,
        seed = t.data.seed,
        csv = t.data.csv,
        latent = t.latent,
        lr_g = t.lr_g,
        lr_d = t.lr_d,
        beta1 = t.beta1,
        epochs = t.epochs,
        d_steps = t.d_steps,
    ))
}
