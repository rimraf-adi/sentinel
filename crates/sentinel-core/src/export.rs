//! Zero Lock-in Exporter: Generates standalone pure bare PyTorch script.

use crate::config::HydraConfig;
use crate::templates::Template;

pub struct ScriptExporter;

impl ScriptExporter {
    /// Generate a standalone pure PyTorch training script from a template and resolved config.
    pub fn export_pytorch_script(
        template: &Template,
        config: &HydraConfig,
    ) -> String {
        let lr = config
            .get_value("training.lr")
            .and_then(|v| v.as_f64())
            .unwrap_or(0.0003);

        let epochs = config
            .get_value("training.epochs")
            .and_then(|v| v.as_i64())
            .unwrap_or(5);

        let batch_size = config
            .get_value("training.batch_size")
            .and_then(|v| v.as_i64())
            .unwrap_or(32);

        let model_name = config
            .get_value("model.name")
            .and_then(|v| v.as_str())
            .unwrap_or("resnet18");

        format!(
            r#"# ==============================================================================
# Standalone PyTorch Training Script
# Generated by Sentinel (Zero Lock-in Exporter)
# Template: {template_id}
# Zero dependencies on Sentinel or Lightning. Run anywhere: `python train.py`
# ==============================================================================

import os
import sys
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, TensorDataset

# --- Hyperparameters ---
MODEL_NAME = "{model_name}"
LEARNING_RATE = {lr}
EPOCHS = {epochs}
BATCH_SIZE = {batch_size}
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

print(f"🚀 Starting standalone training on {{DEVICE}} | Model: {{MODEL_NAME}} | LR: {{LEARNING_RATE}}")

# --- Model Definition ---
class StandardModel(nn.Module):
    def __init__(self, num_classes=10):
        super().__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(3, 16, kernel_size=3, padding=1),
            nn.ReLU(),
            nn.MaxPool2d(2),
            nn.Conv2d(16, 32, kernel_size=3, padding=1),
            nn.ReLU(),
            nn.AdaptiveAvgPool2d((4, 4)),
        )
        self.fc = nn.Linear(32 * 4 * 4, num_classes)

    def forward(self, x):
        return self.fc(self.conv(x).view(x.size(0), -1))

def main():
    model = StandardModel(num_classes=10).to(DEVICE)
    optimizer = optim.AdamW(model.parameters(), lr=LEARNING_RATE, weight_decay=1e-2)
    criterion = nn.CrossEntropyLoss()

    # Synthetic / sample data loader
    torch.manual_seed(42)
    x = torch.randn(64, 3, 32, 32)
    y = torch.randint(0, 10, (64,))
    dataset = TensorDataset(x, y)
    loader = DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=True)

    print(f"📊 Training for {{EPOCHS}} epochs with {{len(loader)}} batches per epoch...")

    initial_loss = None
    final_loss = None

    for epoch in range(1, EPOCHS + 1):
        model.train()
        total_loss = 0.0

        for batch_x, batch_y in loader:
            batch_x, batch_y = batch_x.to(DEVICE), batch_y.to(DEVICE)
            optimizer.zero_grad()
            outputs = model(batch_x)
            loss = criterion(outputs, batch_y)
            loss.backward()
            optimizer.step()
            total_loss += loss.item()

        avg_loss = total_loss / len(loader)
        print(f"[Epoch {{epoch}}/{{EPOCHS}}] Loss: {{avg_loss:.4f}}")

        if initial_loss is None:
            initial_loss = avg_loss
        final_loss = avg_loss

    print("🎉 Training finished successfully!")
    if final_loss < initial_loss:
        print(f"📉 Loss decreased from {{initial_loss:.4f}} to {{final_loss:.4f}}")

if __name__ == "__main__":
    main()
"#,
            template_id = template.template_id,
            model_name = model_name,
            lr = lr,
            epochs = epochs,
            batch_size = batch_size,
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::templates::TemplateRegistry;

    #[test]
    fn test_export_standalone_script() {
        let registry = TemplateRegistry::new();
        let template = registry
            .get("vision/image-classification@v1")
            .expect("find vision template");

        let mut config = HydraConfig::default();
        config.apply_override("training.lr", serde_yaml::Value::Number(serde_yaml::Number::from(0.0005)));
        config.apply_override("training.epochs", serde_yaml::Value::Number(serde_yaml::Number::from(3)));

        let script = ScriptExporter::export_pytorch_script(template, &config);

        assert!(script.contains("LEARNING_RATE = 0.0005"));
        assert!(script.contains("EPOCHS = 3"));
        assert!(script.contains("StandardModel"));
        assert!(!script.contains("import sentinel"));
        assert!(!script.contains("import pytorch_lightning"));
    }
}
